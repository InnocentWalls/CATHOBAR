/**
 * Resolves the PixelIconId for any TickerItem, falling back by source if icon is omitted.
 */
export function resolveItemIcon(item: TickerItem): PixelIconId {
  if (item.icon) return item.icon;
  switch (item.source) {
    case 'weather':
      return 'sun';
    case 'rss':
      return 'news';
    case 'nhk-breaking':
      return item.breaking ? 'alert' : 'news';
    case 'wikipedia':
      return 'wiki';
    case 'mastodon':
      return 'mastodon';
    case 'earthquake':
      return 'quake';
    case 'transit':
      return item.priority === 'high' ? 'train-alert' : 'train';
    case 'market':
      return 'market-flat';
    case 'nowplaying':
      return 'music';
    case 'countdown':
      return 'timer';
    case 'sysmon':
      return 'cpu';
    case 'calendar':
      return 'calendar';
    case 'sensors':
      return 'sensor';
    case 'webhook':
      return item.breaking ? 'alert' : 'webhook';
    case 'push':
      return item.breaking ? 'alert' : 'info';
    case 'clock':
      return 'timer';
  }
}

const MAX_ICON_CACHE = 128;
const iconSpriteCache = new Map<string, HTMLCanvasElement>();

function getCachedIconSprite(
  iconId: PixelIconId,
  pattern: Pattern16,
  primaryColor: string,
  accentColor: string,
): HTMLCanvasElement | null {
  if (typeof document === 'undefined') return null;
  const key = `${iconId}|${primaryColor}|${accentColor}`;
  const cached = iconSpriteCache.get(key);
  if (cached) return cached;

  const canvas = document.createElement('canvas');
  canvas.width = 16;
  canvas.height = 16;
  const sctx = canvas.getContext('2d');
  if (!sctx) return null;

  for (let row = 0; row < 16; row += 1) {
    const line = pattern[row];
    if (!line) continue;
    for (let col = 0; col < 16; col += 1) {
      const ch = line[col];
      if (ch !== '#' && ch !== '+') continue;
      sctx.fillStyle = ch === '+' ? accentColor : primaryColor;
      sctx.fillRect(col, row, 1, 1);
    }
  }

  if (iconSpriteCache.size >= MAX_ICON_CACHE) {
    const oldestKey = iconSpriteCache.keys().next().value;
    if (oldestKey !== undefined) {
      iconSpriteCache.delete(oldestKey);
    }
  }
  iconSpriteCache.set(key, canvas);
  return canvas;
}

/**
 * Draws a 16x16 bitmap pixel icon aligned vertically around centerY.
 */
export function drawPixelIcon(
  ctx: CanvasRenderingContext2D,
  iconId: PixelIconId,
  x: number,
  centerY: number,
  sizePx: number,
  visualMode: VisualMode,
  itemColor: string,
  isHighPriority: boolean,
): void {
  const pattern = PIXEL_ICON_PATTERNS[iconId] ?? PIXEL_ICON_PATTERNS.info;
  const topY = centerY - sizePx * 0.5;

  let primaryColor = itemColor;
  let accentColor = '#ffffff';

  if (visualMode === 'anobar8-vfd') {
    primaryColor = isHighPriority ? '#ffffff' : '#d4d4d4';
    accentColor = '#ffffff';
  } else if (visualMode === 'shinkansen-led') {
    if (iconId === 'alert' || iconId === 'quake' || iconId === 'tsunami' || iconId === 'train-alert' || iconId === 'market-down') {
      primaryColor = '#ff3b30';
      accentColor = '#ff9614';
    } else if (iconId === 'market-up' || iconId === 'train' || iconId === 'news') {
      primaryColor = '#18ff4d';
      accentColor = '#ff9614';
    } else {
      primaryColor = '#ff9614';
      accentColor = '#18ff4d';
    }
  }

  const sprite = getCachedIconSprite(iconId, pattern, primaryColor, accentColor);
  if (sprite) {
    const prevSmooth = ctx.imageSmoothingEnabled;
    ctx.imageSmoothingEnabled = false;
    ctx.drawImage(sprite, Math.floor(x), Math.floor(topY), sizePx, sizePx);
    ctx.imageSmoothingEnabled = prevSmooth;
    return;
  }

  const cell = sizePx / 16;
  for (let row = 0; row < 16; row += 1) {
    const line = pattern[row];
    if (!line) continue;
    for (let col = 0; col < 16; col += 1) {
      const ch = line[col];
      if (ch !== '#' && ch !== '+') continue;
      ctx.fillStyle = ch === '+' ? accentColor : primaryColor;
      const px = Math.floor(x + col * cell);
      const py = Math.floor(topY + row * cell);
      const pw = Math.max(1, Math.ceil(cell * 0.92));
      const ph = Math.max(1, Math.ceil(cell * 0.92));
      ctx.fillRect(px, py, pw, ph);
    }
  }
}
